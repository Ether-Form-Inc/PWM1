/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();

  uint8_t actuator_id = 0x00;

  /* Read all the hardware identifier pins to determine actuator class and actuator id*/
  // Check if user has pulled servo pin low with jumper
  bool is_servo = HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_8) == GPIO_PIN_RESET; // Pin 1
  GPIO_PinState gpio_state_2 = HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_2);      // Pin 2
  GPIO_PinState gpio_state_3 = HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_1);      // Pin 3
  GPIO_PinState gpio_state_4 = HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_0);      // Pin 4

  // Check if any pins are pulled down by user's jumper
  if (gpio_state_2 == GPIO_PIN_RESET)
  {
    actuator_id |= (1 << 0);
  }
  if (gpio_state_3 == GPIO_PIN_RESET)
  {
    actuator_id |= (1 << 1);
  }
  if (gpio_state_4 == GPIO_PIN_RESET)
  {
    actuator_id |= (1 << 2);
  }

  // This needs to be static as we will blow through the stack otherwise
  static STM_can_to_pwm<Stm_can_iface, STM32_system_clock> can_to_pwm{actuator_id, is_servo, 10};
  can_to_pwm.initialize();

  // Ensure uavcan has time to finish node transmission
  HAL_Delay(1);

  // Receive and process can frames
  bool stop{false};
  can_to_pwm.main(stop);

  // This should never be reached
  while (1)
  {
    Error_Handler();
  }
}

